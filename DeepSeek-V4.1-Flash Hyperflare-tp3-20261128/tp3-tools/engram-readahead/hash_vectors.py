"""Emit Rust test vectors from b12x's CPU Engram hash oracle (reference.py), DS41 geometry.

Run: CUDA_VISIBLE_DEVICES= <venv>/bin/python -I hash_vectors.py <b12x sequence dir> > body; the Rust file is the two SPDX lines + body (helios/src/engram/row_ids_vectors.rs).
Loads geometry.py / reference.py / ple_hash/reference.py by path (no flashinfer import).
"""
import importlib.util, random, sys, types

seq = sys.argv[1]
def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec); sys.modules[name] = mod; spec.loader.exec_module(mod); return mod
for pkg in ("s", "s.ple_hash", "s.engram"):
    m = types.ModuleType(pkg); m.__path__ = []; sys.modules[pkg] = m
load("s.ple_hash.reference", f"{seq}/ple_hash/reference.py")
geo = load("s.engram.geometry", f"{seq}/engram/geometry.py")
ref = load("s.engram.reference", f"{seq}/engram/reference.py")

g = geo.build_geometry()  # DS41 defaults: layers (1, 14), 16M base, 99,092 compressed vocabulary
rng = random.Random(20261118)
V = 64
token_map = [rng.randrange(g.compressed_vocab_size) for _ in range(V)]
pad = token_map[2]
# One request, fresh (history = pad), 40 query tokens: some excluded (mask False), some token 2 (pad id).
tokens = [rng.randrange(V) for _ in range(40)]
tokens[5] = 2
mask = [True] * 40
for i in (11, 12, 30):
    mask[i] = False
starts = [0, 40]
print("// generated by tp3-tools/engram-readahead/hash_vectors.py from b12x sequence/engram/reference.py")
print(f"const TOKEN_MAP: [u32; {V}] = {token_map};")
print(f"const TOKENS: [u32; 40] = {tokens};")
print(f"const EXCLUDED: [usize; 3] = [11, 12, 30];")
for li, layer in enumerate(g.layer_ids):
    print(f"const MULTIPLIERS_{layer}: [u64; 4] = {list(g.multipliers[li])};")
    print(f"const PRIMES_{layer}: [u64; 24] = {list(g.primes[li])};")
    print(f"const OFFSETS_{layer}: [u64; 24] = {list(g.offsets[li])};")
    print(f"const ROWS_{layer}: u64 = {g.num_embeddings[li]};")
    # fresh request: committed history is the pad value
    rows = ref.hash_reference(tokens, mask, starts, [0], [[pad, pad, pad]], token_map, g, layer)
    print(f"const EXPECTED_{layer}_FRESH: [[i64; 24]; 40] = {rows.tolist()};")
    # continuation chunk: queries 20..40 with committed history = compressed tokens 17..20
    comp = [token_map[t] if k else -1 for t, k in zip(tokens, mask)]
    rows2 = ref.hash_reference(tokens[20:], mask[20:], [0, 20], [0], [comp[17:20]], token_map, g, layer)
    assert rows2.tolist() == rows.tolist()[20:], "chunked history must reproduce the whole-prompt rows"
